from __future__ import annotations

from textwrap import dedent

import pandas as pd

from .config import ReversedeConfig


def _comment_block(alerts: list[str]) -> str:
    """Render arbitrary alert text as comments without creating source lines."""
    lines: list[str] = []
    for alert in alerts:
        alert_lines = str(alert).splitlines() or [""]
        lines.extend(f"# ALERT: {line}" for line in alert_lines)
    return "\n        ".join(lines)


def generate_blueprint(
    candidates: pd.DataFrame,
    stress: pd.DataFrame,
    target: str | None,
    alerts: list[str],
    config: ReversedeConfig,
) -> str:
    selected = candidates[candidates["selected"]]
    stress_map = stress.set_index("column").to_dict(orient="index") if not stress.empty else {}
    numeric_standard: list[str] = []
    numeric_robust: list[str] = []
    numeric_string: list[str] = []
    categorical_low: list[str] = []
    categorical_high: list[str] = []
    datetime_columns: list[str] = []
    for row in selected.to_dict(orient="records"):
        column = str(row["column"])
        kind = str(row["kind"])
        detail = stress_map.get(column, {})
        if kind == "numeric":
            if (
                float(detail.get("iqr_outlier_fraction", 0.0) or 0.0)
                > config.outlier_fraction_threshold
            ):
                numeric_robust.append(column)
            else:
                numeric_standard.append(column)
        elif kind == "numeric_string":
            numeric_string.append(column)
        elif kind == "categorical":
            target_group = (
                categorical_high
                if int(row["unique_values"]) > config.high_cardinality_levels
                else categorical_low
            )
            target_group.append(column)
        elif kind == "datetime":
            datetime_columns.append(column)

    header = _comment_block(alerts)
    groups = {
        "NUMERIC_STANDARD": numeric_standard,
        "NUMERIC_ROBUST": numeric_robust,
        "NUMERIC_STRING": numeric_string,
        "CATEGORICAL_LOW": categorical_low,
        "CATEGORICAL_HIGH": categorical_high,
        "DATETIME_COLUMNS": datetime_columns,
    }
    min_frequency = None if config.rare_category_fraction == 0 else config.rare_category_fraction
    literals = "\n        ".join(f"{name} = {value!r}" for name, value in groups.items())
    return dedent(
        f'''\
        # Generated by Reversede. Review semantics before fitting.
        {header}
        import numpy as np
        import pandas as pd
        from sklearn.compose import ColumnTransformer
        from sklearn.impute import SimpleImputer
        from sklearn.pipeline import Pipeline
        from sklearn.preprocessing import (
            FunctionTransformer,
            OneHotEncoder,
            RobustScaler,
            StandardScaler,
        )

        TARGET = {target!r}
        MIN_FREQUENCY = {min_frequency!r}
        MAX_CATEGORIES = {config.max_categorical_levels!r}
        {literals}

        def _to_numeric(X):
            frame = pd.DataFrame(X).apply(
                lambda column: pd.to_numeric(
                    column.astype("string").str.strip().str.replace(",", ".", regex=False),
                    errors="coerce",
                )
            )
            return frame.to_numpy(dtype=float)

        def _to_string(X):
            frame = pd.DataFrame(X).astype("string")
            return frame.to_numpy(dtype=object, na_value=np.nan)

        def _date_parts(X):
            frame = pd.DataFrame(X)
            parts = []
            for column in frame.columns:
                value = pd.to_datetime(frame[column], errors="coerce", utc=True)
                month = value.dt.month.astype(float)
                weekday = value.dt.dayofweek.astype(float)
                parts.extend([
                    value.dt.year.astype(float).to_numpy(),
                    np.sin(2 * np.pi * month / 12).to_numpy(),
                    np.cos(2 * np.pi * month / 12).to_numpy(),
                    np.sin(2 * np.pi * weekday / 7).to_numpy(),
                    np.cos(2 * np.pi * weekday / 7).to_numpy(),
                    value.dt.day.astype(float).to_numpy(),
                ])
            return np.column_stack(parts) if parts else np.empty((len(frame), 0))

        def build_preprocessor():
            transformers = []
            if NUMERIC_STANDARD:
                transformers.append(("numeric_standard", Pipeline([
                    ("imputer", SimpleImputer(strategy="median", add_indicator=True)),
                    ("scaler", StandardScaler()),
                ]), NUMERIC_STANDARD))
            if NUMERIC_ROBUST:
                transformers.append(("numeric_robust", Pipeline([
                    ("imputer", SimpleImputer(strategy="median", add_indicator=True)),
                    ("scaler", RobustScaler()),
                ]), NUMERIC_ROBUST))
            if NUMERIC_STRING:
                transformers.append(("numeric_string", Pipeline([
                    ("coerce", FunctionTransformer(_to_numeric, validate=False)),
                    ("imputer", SimpleImputer(strategy="median", add_indicator=True)),
                    ("scaler", StandardScaler()),
                ]), NUMERIC_STRING))
            if CATEGORICAL_LOW:
                transformers.append(("categorical_low", Pipeline([
                    ("string", FunctionTransformer(_to_string, validate=False)),
                    ("imputer", SimpleImputer(strategy="most_frequent")),
                    ("onehot", OneHotEncoder(handle_unknown="ignore")),
                ]), CATEGORICAL_LOW))
            if CATEGORICAL_HIGH:
                transformers.append(("categorical_high", Pipeline([
                    ("string", FunctionTransformer(_to_string, validate=False)),
                    ("imputer", SimpleImputer(strategy="most_frequent")),
                    ("onehot", OneHotEncoder(
                        handle_unknown="ignore",
                        min_frequency=MIN_FREQUENCY,
                        max_categories=MAX_CATEGORIES,
                    )),
                ]), CATEGORICAL_HIGH))
            if DATETIME_COLUMNS:
                transformers.append(("datetime", Pipeline([
                    ("parts", FunctionTransformer(_date_parts, validate=False)),
                    ("imputer", SimpleImputer(strategy="median", add_indicator=True)),
                    ("scaler", StandardScaler()),
                ]), DATETIME_COLUMNS))
            if not transformers:
                raise ValueError("No eligible tabular features; review the Reversede report.")
            return ColumnTransformer(transformers=transformers, remainder="drop")

        class FeatureExtractor:
            """Sklearn-compatible extractor; fit only on each training fold."""

            def __init__(self):
                self.preprocessor = build_preprocessor()

            def fit(self, X, y=None):
                self.preprocessor.fit(X, y)
                return self

            def transform(self, X):
                return self.preprocessor.transform(X)

            def fit_transform(self, X, y=None):
                return self.preprocessor.fit_transform(X, y)
        '''
    )
